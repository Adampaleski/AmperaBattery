#!/usr/bin/env python3
"""tools/parts.json + tools/parts.js <- docs/PARTS.yaml (the canonical parts list).

docs/PARTS.yaml is generated by /workspace/teryx/tools_parts/build_parts.py; never hand-edit it.
parts.json is for scripts (check_parts.py); parts.js sets window.PARTS / window.PARTS_META and is
embedded in tools/wiring.html so a diagram click resolves part id -> name/model/status/specs.
Run at build time (build_wiring.py calls build()); outputs are committed.
"""
import json, pathlib, yaml
R = pathlib.Path(__file__).resolve().parent
SRC = R.parent / "docs" / "PARTS.yaml"

def load():
    d = yaml.safe_load(SRC.read_text())
    return d.get("meta", {}), d["parts"]

def build():
    meta, parts = load()
    m = {k: meta[k] for k in ("title", "generated", "generator", "keying") if k in meta}
    m["source"] = "docs/PARTS.yaml"
    m["count"] = len(parts)
    m["conflicts"] = sorted(k for k, v in parts.items() if v.get("conflict"))  # same rule as build_parts.py
    out = {"meta": m, "parts": parts}
    js = json.dumps(out, ensure_ascii=False, indent=1, default=str)
    (R / "parts.json").write_text(js + "\n")
    (R / "parts.js").write_text("// GENERATED by tools/build_parts_json.py from docs/PARTS.yaml — do not edit\n"
                                "window.PARTS_META=" + json.dumps(m, ensure_ascii=False, default=str) + ";\n"
                                "window.PARTS=" + json.dumps(parts, ensure_ascii=False, default=str) + ";\n")
    return out

if __name__ == "__main__":
    o = build()
    print(f"parts.json/parts.js: {o['meta']['count']} parts, conflicts {len(o['meta']['conflicts'])}: {', '.join(o['meta']['conflicts'])}")
