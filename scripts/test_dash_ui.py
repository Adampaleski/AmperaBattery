# python3 scripts/test_dash_ui.py [shots_dir] — browser UI checks for tools/bms_sim.html + tools/dash.html (Playwright + Chrome)
import sys, os, pathlib
from playwright.sync_api import sync_playwright
root = pathlib.Path(__file__).resolve().parent.parent / 'tools'
shots = sys.argv[1] if len(sys.argv) > 1 else None
n = f = 0
def ok(c, m):
    global n, f
    n += 1
    if not c: f += 1
    print(('PASS' if c else 'FAIL'), 'ui', m)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=os.environ.get('CHROME', '/usr/bin/google-chrome'), args=['--no-sandbox'])
    ctx = b.new_context(viewport={'width': 1366, 'height': 1024}); pg = ctx.new_page()
    errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.on('dialog', lambda d: d.accept())
    pg.goto((root / 'bms_sim.html').as_uri()); pg.wait_for_selector('#dashHost .tdash'); pg.wait_for_timeout(600)
    D = '#dashHost '
    ok(pg.is_visible(D + '.simp') and pg.is_visible(D + '.dock'), 'sim: SIMULATOR panel and quick-button dock visible on Dash tab')
    if shots: pg.screenshot(path=f'{shots}/home.png', full_page=True)
    # quick buttons toggle
    pg.click(D + '[data-q="lights"]'); pg.wait_for_timeout(300)
    ok('on' in pg.get_attribute(D + '[data-q="lights"]', 'class'), 'quick Lights toggles on')
    pg.click(D + '[data-q="lights"]'); pg.wait_for_timeout(300)
    ok('on' not in pg.get_attribute(D + '[data-q="lights"]', 'class'), 'quick Lights toggles off')
    pg.click(D + '[data-seat="driver"]'); pg.wait_for_timeout(200)
    ok(pg.inner_text(D + '[data-f="lv_driver"]').startswith('Low'), 'quick seat heater: Off → Low')
    pg.click(D + '[data-q="fan"]'); pg.wait_for_timeout(500)
    ok(pg.inner_text(D + '[data-f="q_fan"]') in ('override', 'on'), 'quick Fan override turns the fan on')
    pg.click(D + '[data-q="fan"]')
    pg.click(D + '[data-q="diff"]'); pg.wait_for_timeout(300)
    ok('in 4WD' in pg.inner_text(D + '[data-f="toast"]'), 'quick Diff lock refused in 2WD with the reason shown')
    pg.click(D + '[data-q="4wd"]'); pg.wait_for_timeout(3500)
    ok(pg.inner_text(D + '[data-f="q_4wd"]') == '4WD', 'quick 4WD engages when stopped')
    pg.click(D + '[data-q="4wd"]'); pg.wait_for_timeout(3500)
    # hard launch: speed / rpm rising
    pg.click(D + '[data-sc="launch"]'); pg.wait_for_timeout(3000)
    s1 = float(pg.inner_text(D + '[data-f="spd"]') or 0); r1 = pg.inner_text(D + '[data-f="rpm"]')
    pg.wait_for_timeout(2500)
    s2 = float(pg.inner_text(D + '[data-f="spd"]') or 0); r2 = pg.inner_text(D + '[data-f="rpm"]')
    ok(s2 > s1 > 0 and float(r2) > float(r1) > 0, f'hard launch: speed {s1}→{s2} mph, RPM {r1}→{r2} rising')
    q4 = pg.get_attribute(D + '[data-q="4wd"]', 'class')
    ok('dis' in q4, '4WD quick button greyed out while moving')
    # regen stop: negative amps
    pg.click(D + '[data-sc="regen"]'); amps = []
    for i in range(8):
        pg.wait_for_timeout(250); amps.append(pg.evaluate('S.packA'))
    ok(min(amps) < -5, f'regen stop: pack amps go negative (min {min(amps):.1f} A)')
    ok('regen' in pg.inner_text(D + '[data-f="sro"]'), 'sim readout shows regen A')
    pg.click(D + '[data-sc="coast"]')
    # menu sections
    pg.click(D + '[data-q="menu"]')
    for k in ['batt', 'chg', 'drive', 'lights', 'wd', 'flt', 'cool', 'veh', 'disp', 'diag', 'about']:
        pg.click(D + f'[data-sec="{k}"]'); pg.wait_for_timeout(250)
        ok(pg.is_visible(D + f'[data-s2="{k}"]'), f'menu opens section {k}')
    pg.click(D + '[data-sec="batt"]'); pg.wait_for_timeout(400)
    ok(pg.locator(D + '.cg i').count() == 144, 'Battery: 144 cells in the grid')
    if shots: pg.screenshot(path=f'{shots}/battery.png')
    pg.click(D + '[data-sec="drive"]'); pg.wait_for_timeout(400)
    ok(pg.locator(D + '.crv svg').count() == 5, 'Drive & Kelly: 5 cutback curves')
    pg.click(D + '[data-sec="veh"]'); pg.wait_for_timeout(300)
    ok('8.75' in pg.inner_text(D + '[data-s2="veh"]') and 'Diff ratio' in pg.inner_text(D + '[data-s2="veh"]'), 'Vehicle: Diff ratio 4.375, total 8.75 shown')
    if shots: pg.screenshot(path=f'{shots}/menu_vehicle.png')
    small = pg.evaluate("""[...document.querySelectorAll('#dashHost .mnu *')].filter(e=>e.offsetParent&&e.childNodes.length&&[...e.childNodes].some(n=>n.nodeType===3&&n.textContent.trim())&&parseFloat(getComputedStyle(e).fontSize)<18).length""")
    ok(small == 0, f'menu: no visible text under 18 px ({small})')
    pg.click(D + '[data-f="mclose"]')
    # quick-button bar pinned and usable on every menu section
    pg.click(D + '[data-q="menu"]')
    cover = """(k)=>{const b=document.querySelector('#dashHost [data-q="'+k+'"]');b.scrollIntoView({block:'nearest'});const r=b.getBoundingClientRect(),e=document.elementFromPoint(r.x+r.width/2,r.y+r.height/2);return r.width>40&&!!e&&b.contains(e);}"""
    for k in ['batt', 'chg', 'drive', 'lights', 'wd', 'flt', 'cool', 'veh', 'disp', 'diag', 'about']:
        pg.click(D + f'[data-sec="{k}"]'); pg.wait_for_timeout(150)
        top = pg.evaluate(cover, 'lights')
        pg.click(D + '[data-q="lights"]'); pg.wait_for_timeout(250)
        on = 'on' in pg.get_attribute(D + '[data-q="lights"]', 'class')
        pg.click(D + '[data-q="lights"]'); pg.wait_for_timeout(250)
        ok(top and on and pg.is_visible(D + f'[data-s2="{k}"]'), f'quick bar pinned + Lights usable on section {k}')
    pg.click(D + '[data-sec="veh"]'); pg.wait_for_timeout(150)
    # split view: default left = cluster, right = last opened section
    pg.click(D + '[data-q="split"]'); pg.wait_for_timeout(400)
    ok(pg.evaluate("document.querySelector('#dashHost .tdash').classList.contains('splitOn')") and pg.input_value(D + '[data-f="pickL"]') == 'home' and pg.input_value(D + '[data-f="pickR"]') == 'veh', 'split: default left = cluster, right = last opened (veh)')
    pg.select_option(D + '[data-f="pickR"]', 'chg'); pg.wait_for_timeout(500)
    ok(pg.is_visible(D + '[data-f="pbR"] [data-s2="chg"]') and pg.is_visible(D + '[data-f="pbL"] [data-f="spd"]'), 'split: cluster left + charging right both visible')
    ok(pg.evaluate(cover, 'fan'), 'split: quick bar pinned and uncovered')
    pg.select_option(D + '[data-f="pickL"]', 'chg'); pg.wait_for_timeout(300)
    ok(pg.input_value(D + '[data-f="pickL"]') == 'chg' and pg.input_value(D + '[data-f="pickR"]') == 'home', 'split: picking the other pane\'s section swaps them')
    pg.select_option(D + '[data-f="pickL"]', 'home'); pg.wait_for_timeout(300)
    pg.reload(); pg.wait_for_selector('#dashHost .tdash'); pg.wait_for_timeout(900)
    ok(pg.evaluate("document.querySelector('#dashHost .tdash').classList.contains('splitOn')") and pg.input_value(D + '[data-f="pickL"]') == 'home' and pg.input_value(D + '[data-f="pickR"]') == 'chg', 'split: choice saved across reload (cluster + charging)')
    pg.set_viewport_size({'width': 800, 'height': 1100}); pg.wait_for_timeout(300)
    bl = pg.locator(D + '[data-pane="L"]').bounding_box(); br = pg.locator(D + '[data-pane="R"]').bounding_box()
    ok(br['y'] >= bl['y'] + bl['height'] - 2, 'split: panes stack vertically on a narrow screen')
    pg.set_viewport_size({'width': 1366, 'height': 1024})
    pg.click(D + '[data-q="split"]'); pg.wait_for_timeout(300)
    ok(not pg.evaluate("document.querySelector('#dashHost .tdash').classList.contains('splitOn')") and pg.is_visible(D + '.stage>.home'), 'split off: home cluster back in place')
    pg.evaluate("localStorage.removeItem('teryxDashSplit')")
    # full-screen dash (dash.html?src=sim, fed by the open sim tab): home with the bar, then split cluster + charging
    fs = ctx.new_page()
    fs.set_viewport_size({'width': 1366, 'height': 1024}); fs.goto((root / 'dash.html').as_uri() + '?src=sim'); fs.wait_for_timeout(1500)
    fs.click('[data-f="simcol"]'); fs.wait_for_timeout(300)
    ok(fs.is_visible('.dock [data-q="lights"]') and fs.inner_text('[data-f="spd"]') != '—', 'full-screen dash: live sim data and quick bar on home')
    if shots: fs.screenshot(path=f'{shots}/home_bar.png')
    fs.click('[data-q="split"]'); fs.select_option('[data-f="pickL"]', 'home'); fs.select_option('[data-f="pickR"]', 'chg'); fs.wait_for_timeout(800)
    ok(fs.is_visible('[data-f="pbR"] [data-s2="chg"]') and fs.is_visible('.dock [data-q="fan"]'), 'full-screen dash: split cluster + charging with the quick bar')
    if shots: fs.screenshot(path=f'{shots}/split_cluster_charging.png')
    fs.click('[data-q="split"]'); fs.click('[data-f="simcol"]'); fs.evaluate("localStorage.removeItem('teryxDashSplit')"); fs.close()
    # BMS thresholds card (Settings tab): real Thresholds.h validation via wasm, live + saved
    pg.click('.tab[data-t="settings"]'); pg.wait_for_timeout(300)
    T = '#thrT tr[data-k="ocA"] '
    ok(pg.locator('#thrT tr[data-k]').count() == 21 and pg.locator('#thrT tr[data-k="floorV"] .tag').count() == 1, 'thresholds: 21 keys listed, PLACEHOLDER tag on floorV')
    pg.fill(T + 'input', '600'); pg.press(T + 'input', 'Enter'); pg.wait_for_timeout(300)
    ok('saved: ocA=600' in pg.inner_text('#thrMsg') and 'SET' in pg.inner_text(T) and pg.evaluate('S.cfg.overA') == 600, 'thresholds: ocA 600 applied live, SET tag')
    pg.fill(T + 'input', '700'); pg.press(T + 'input', 'Enter'); pg.wait_for_timeout(300)
    m = pg.inner_text('#thrMsg')
    ok('REFUSED' in m and 'tighten-only' in m and 'bad' in pg.get_attribute('#thrMsg', 'class') and pg.input_value(T + 'input') == '600', 'thresholds: ocA 700 refused with reason (tighten-only), value kept')
    if shots: pg.screenshot(path=f'{shots}/thresholds.png', full_page=True)
    pg.reload(); pg.wait_for_selector('#dashHost .tdash'); pg.wait_for_timeout(900)
    pg.click('.tab[data-t="settings"]'); pg.wait_for_timeout(300)
    ok(pg.input_value(T + 'input') == '600' and pg.evaluate('S.cfg.overA') == 600, 'thresholds: ocA 600 survives page reload')
    pg.click(T + '[data-r]'); pg.wait_for_timeout(300)
    ok(pg.input_value(T + 'input') == '650' and 'back to default 650' in pg.inner_text('#thrMsg'), 'thresholds: per-key Reset restores 650')
    pg.click('#thrX'); pg.wait_for_timeout(300)
    ok('0 of 21 changed' in pg.inner_text('#thrSum'), 'thresholds: Reset all')
    pg.click('.tab[data-t="faults"]'); pg.wait_for_timeout(300)
    ok('Last derate' in pg.inner_text('#fder'), 'faults tab: last derate line shown')
    pg.click('.tab[data-t="cluster"]'); pg.wait_for_timeout(200)
    pg.click(D + '[data-q="menu"]'); pg.click(D + '[data-sec="flt"]'); pg.wait_for_timeout(400)
    ok('Last derate' in pg.inner_text(D + '[data-f="mfd"]'), 'dash Faults & log: derate now / last derate panel')
    pg.click(D + '[data-f="mclose"]')
    # drive modes (PROPOSED pedal maps)
    ok(pg.locator('#cgsel button').count() == 8 and pg.locator(D + '[data-sg]').count() == 8 and pg.locator('#modeT tr[data-mode]').count() == 8,
       'drive modes: 7 modes + R in sim selector, dash sim panel, Settings profile table')
    J = lambda js: pg.evaluate(js)
    on = lambda: J("document.querySelector('#cgsel .on').dataset.g")
    J("document.querySelector('#cgsel [data-g=\"KID\"]').click()"); ok(on() == 'H', 'Kid refused until a Kid PIN is set')
    J("document.getElementById('kidPinSet').value='2468';document.getElementById('kidPinBtn').click();document.querySelector('#cgsel [data-g=\"KID\"]').click()")
    ok(on() == 'KID', 'Kid PIN set -> Kid mode entered')
    sv = J("localStorage.getItem('teryx.modes.v1')")
    ok('2468' not in sv and '"mode":"KID"' in sv, 'sim storage: mode KID saved, PIN only as hash')
    pg.reload(); pg.wait_for_selector('#dashHost .tdash'); pg.wait_for_timeout(600)
    ok(on() == 'KID', 'reload (reboot): Kid stays Kid')
    J("document.querySelector('#cgsel [data-g=\"H\"]').click()"); ok(on() == 'KID', 'leave Kid without PIN: refused')
    J("document.getElementById('kidPin').value='1111';document.querySelector('#cgsel [data-g=\"H\"]').click()"); ok(on() == 'KID', 'leave Kid with wrong PIN: refused')
    J("document.getElementById('kidPin').value='2468';document.querySelector('#cgsel [data-g=\"H\"]').click()"); ok(on() == 'H', 'leave Kid with the PIN: High')
    J("localStorage.removeItem('teryx.modes.v1')")
    # park detection (docs/PARK_BRAKE.md)
    J("document.getElementById('cpark').checked=false;document.getElementById('cpark').dispatchEvent(new Event('change'))"); pg.wait_for_timeout(400)
    ok('BLOCKED' in J("document.getElementById('pkdet').textContent"), 'park released: precharge shown BLOCKED')
    J("document.getElementById('cpark').checked=true;document.getElementById('cpark').dispatchEvent(new Event('change'))"); pg.wait_for_timeout(400)
    ok('PARKED' in J("document.getElementById('pkdet').textContent"), 'park set + neutral + 0 RPM: PARKED')
    J("document.getElementById('cparkb').checked=true"); pg.wait_for_timeout(600)
    ok('PARK-CONTACT-DISAGREE' in J("document.getElementById('pkdet').textContent"), 'contact B open: PARK-CONTACT-DISAGREE shown')
    J("document.getElementById('cparkb').checked=false;document.getElementById('cparkclr').click()")
    ok(not errs, 'no page errors ' + '; '.join(errs[:3]))
    # dash.html real mode: no sim panel; ?src=sim: panel present
    d = b.new_page(viewport={'width': 1366, 'height': 1024}); d.goto((root / 'dash.html').as_uri() + '?src=none'); d.wait_for_timeout(500)
    ok(d.locator('.simp').count() == 0, 'dash.html real mode: no SIMULATOR panel in the DOM')
    d.goto((root / 'dash.html').as_uri() + '?src=sim'); d.wait_for_timeout(500)
    ok(d.locator('.simp').count() == 1, 'dash.html?src=sim: SIMULATOR panel present')
    b.close()
print(f'{n-f}/{n} ui')
sys.exit(1 if f else 0)
